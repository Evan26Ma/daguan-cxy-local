import fs from "node:fs/promises";
import path from "node:path";
import { createHash, randomUUID } from "node:crypto";
import { syncOfficialQuestionBank } from "./official-question-bank.mjs";
import { NATIVE_SOLUTIONS_FILE } from "../shared/native-solutions.mjs";

const DATA_FILES = ["manifest.json", "lecture-video-mappings.json", "paradiyu-linear-video.json"];
const REQUIRED_FILES = [...DATA_FILES, "categories.json", "category_questions.json", "id_index.json", "search_index.json"];

export async function createQuestionBankUpdater({ dataDir, bundledDataDir, enabled, onUpdate = () => {} }) {
  const bankDir = path.join(dataDir, "question-bank");
  const versionsDir = path.join(bankDir, "versions");
  const pointerFile = path.join(bankDir, "current.json");
  let current = null;
  let running = null;
  let timer = null;
  let closing = false;
  const abort = new AbortController();

  async function validVersion(pointer) {
    if (!pointer || !/^[0-9a-f-]{36}$/.test(pointer.id)) return false;
    const root = path.join(versionsDir, pointer.id);
    try {
      const manifest = JSON.parse(await fs.readFile(path.join(root, "manifest.json"), "utf8"));
      if (!Number.isInteger(manifest.total) || manifest.total <= 0) return false;
      for (const file of REQUIRED_FILES) await fs.access(path.join(root, file));
      for (const shard of Object.values(manifest.shards || {})) await fs.access(path.join(root, shard.file));
      return true;
    } catch { return false; }
  }

  try {
    const pointer = JSON.parse(await fs.readFile(pointerFile, "utf8"));
    if (await validVersion(pointer)) current = pointer;
  } catch {}

  async function bundledFingerprint() {
    const digest = createHash("sha256");
    for (const file of DATA_FILES) digest.update(await fs.readFile(path.join(bundledDataDir, file)));
    const classifications = await fs.readFile(path.join(bundledDataDir, "official-orphan-classifications.json"))
      .catch(error => { if (error.code === "ENOENT") return Buffer.alloc(0); throw error; });
    digest.update(classifications);
    const overlayDir = path.join(bundledDataDir, "local_question_banks");
    const files = await fs.readdir(overlayDir).catch(() => []);
    for (const file of files.filter(name => name.endsWith(".json")).sort()) {
      digest.update(file);
      digest.update(await fs.readFile(path.join(overlayDir, file)));
    }
    const nativeSolutions = await fs.readFile(path.join(bundledDataDir, NATIVE_SOLUTIONS_FILE))
      .catch(error => { if (error.code === "ENOENT") return null; throw error; });
    if (nativeSolutions) {
      digest.update(NATIVE_SOLUTIONS_FILE);
      digest.update(nativeSolutions);
    }
    return digest.digest("hex");
  }

  async function update() {
    if (!enabled || closing) return null;
    if (running) return running;
    running = (async () => {
      const bundledHash = await bundledFingerprint();
      const id = randomUUID();
      const stage = path.join(bankDir, `stage-${id}`);
      try {
        const result = await syncOfficialQuestionBank({
          targetDir: stage, overlayDir: bundledDataDir,
          fallbackAssetsDir: path.join(bundledDataDir, "assets"), signal: abort.signal,
          currentFingerprint: current?.bundledHash === bundledHash ? current.fingerprint : null,
        });
        if (result.unchanged || closing || abort.signal.aborted) return result;
        await fs.mkdir(versionsDir, { recursive: true });
        await fs.rename(stage, path.join(versionsDir, id));
        const pointer = { id, fingerprint: result.fingerprint, bundledHash,
          sourceTotal: result.sourceTotal, total: result.total, missingAssets: result.missingAssets,
          native_solution_stats: result.native_solution_stats,
          updatedAt: new Date().toISOString() };
        const tempPointer = `${pointerFile}.tmp-${id}`;
        await fs.writeFile(tempPointer, `${JSON.stringify(pointer)}\n`);
        await fs.rename(tempPointer, pointerFile);
        current = pointer;
        onUpdate(pointer);
        return pointer;
      } finally {
        // Only a staging path generated by this updater can be removed.
        if (path.dirname(stage) === bankDir && path.basename(stage) === `stage-${id}`) {
          await fs.rm(stage, { recursive: true, force: true }).catch(() => {});
        }
      }
    })().finally(() => { running = null; });
    return running;
  }

  function start() {
    if (!enabled) return;
    const initial = setTimeout(() => update().catch(error => console.warn(`题库自动更新失败：${error.message}`)), 0);
    initial.unref();
    timer = setInterval(() => update().catch(error => console.warn(`题库自动更新失败：${error.message}`)), 24 * 60 * 60 * 1000);
    timer.unref();
  }

  async function stop() {
    closing = true;
    abort.abort();
    if (timer) clearInterval(timer);
    if (running) await running.catch(() => {});
  }

  function dataRoot(id = null) {
    if (id === "bundled" || (!id && !current)) return bundledDataDir;
    const version = id || current?.id;
    if (!version || !/^[0-9a-f-]{36}$/.test(version)) return null;
    return path.join(versionsDir, version);
  }

  return {
    start, stop, update, dataRoot,
    status: () => ({ enabled: Boolean(enabled), activeId: current?.id || "bundled",
      sourceTotal: current?.sourceTotal || null, total: current?.total || null,
      missingAssets: current?.missingAssets ?? null, updatedAt: current?.updatedAt || null,
      native_solution_stats: current?.native_solution_stats || null }),
  };
}
